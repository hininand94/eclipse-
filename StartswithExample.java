public class StartswithExample {
	    public static void main(String[] args) {
	        String str = "Hello Java";

	        if (str.startsWith("Hello")) {
	            System.out.println("Starts with Hello");
	        } else {
	            System.out.println("Does not start with Hello");
	        }
	    }
	 }
